"""Regenerate every CAD output from the product models in cad/products/.

    python -m cad.generate          # write all outputs
    python -m cad.generate --check  # fail if committed outputs are stale

Per product (cam = camera glasses, vr = VR headset):
    cad/out/<key>/hologram_<key>.ifc           open directly in Revit (File > Open > IFC)
    cad/revit/hologram_<key>_model.json        read by cad/revit/build_hologram_family.py
    docs/<key>/drawings/*.svg                  assembly, exploded, orthographic, wiring
    docs/<key>/bom.md, docs/<key>/wiring.md    bill of materials and pin table
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .ifc_writer import build_ifc
from .product import Product
from .products import PRODUCTS
from .schematic import draw_schematic
from .svg_draw import draw_assembly, draw_exploded, draw_orthographic

ROOT = Path(__file__).resolve().parent.parent


def model_json(product: Product) -> str:
    env = product.envelope()
    parts = []
    for p in product.parts:
        solids = []
        for s in p.solids:
            loops = [[[round(c, 4) for c in s.point3(pt, s.start)] for pt in loop] for loop in s.loops()]
            solids.append({"plane": s.plane, "normal": list(s.normal), "depth": round(s.depth, 4), "loops": loops})
        parts.append({"id": p.id, "name": p.name, "group": p.group, "material": p.material, "solids": solids})
    doc = {
        "name": product.name,
        "key": product.key,
        "units": "mm",
        "axes": "X = wearer's right, Y = forward, Z = up",
        "envelope_mm": {"width": env.width, "depth": env.depth, "height": env.height},
        "materials": {k: {"name": m.name, "rgb": list(m.rgb), "transparency": m.transparency}
                      for k, m in product.materials.items()},
        "parts": parts,
    }
    return json.dumps(doc, indent=1) + "\n"


def bom_md(product: Product) -> str:
    used: dict[str, list[str]] = {}
    for p in product.parts:
        if p.bom:
            used.setdefault(p.bom, []).append(p.name)
    lines = [
        f"# {product.name}: bill of materials",
        "",
        f"<!-- Generated by `python -m cad.generate` from cad/products/{product.key}.py. Edit the model, not this file. -->",
        "",
        "Part numbers are examples; any equivalent with the same size and interface works.",
        "",
        "| # | Qty | Item | Spec | Model parts | Notes |",
        "|---|-----|------|------|-------------|-------|",
    ]
    for i, line in enumerate(product.bom, 1):
        parts = ", ".join(sorted(set(used.get(line.key, [])))) or "-"
        lines.append(f"| {i} | {line.qty} | {line.item} | {line.spec} | {parts} | {line.notes} |")
    return "\n".join(lines) + "\n"


def wiring_md(product: Product) -> str:
    def end(e: tuple[str, str]) -> str:
        dev, pin = e
        if dev == "pi":
            if pin.isdigit():
                return f"{product.compute} pin {pin} ({product.header[int(pin)]})"
            return f"{product.compute} {pin}"
        return f"{product.devices[dev].name} `{pin}`"

    lines = [
        f"# {product.name}: wiring",
        "",
        f"<!-- Generated by `python -m cad.generate` from cad/products/{product.key}.py. Edit the model, not this file. -->",
        "",
        f"Pin numbers are physical pin positions on the {product.compute}.",
        "See `drawings/04_wiring.svg` for the schematic.",
        "",
        "| Type | From | To | Notes |",
        "|------|------|----|-------|",
    ]
    for w in product.wires:
        lines.append(f"| {w.kind} | {end(w.a)} | {end(w.b)} | {w.note} |")
    lines += ["", "## Where each module lives", "", "| Module | Location |", "|--------|----------|"]
    lines += [f"| {d.name} | {d.location} |" for d in product.devices.values()]
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for p in PRODUCTS:
        docs = ROOT / "docs" / p.key
        out.update({
            ROOT / f"cad/out/{p.key}/hologram_{p.key}.ifc": build_ifc(p),
            ROOT / f"cad/revit/hologram_{p.key}_model.json": model_json(p),
            docs / "drawings/01_assembly.svg": draw_assembly(p),
            docs / "drawings/02_exploded.svg": draw_exploded(p),
            docs / "drawings/03_orthographic.svg": draw_orthographic(p),
            docs / "drawings/04_wiring.svg": draw_schematic(p),
            docs / "bom.md": bom_md(p),
            docs / "wiring.md": wiring_md(p),
        })
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if any output is out of date")
    args = parser.parse_args(argv)

    stale = []
    for path, content in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and stale:
        print("Out of date (run python -m cad.generate):", *stale, sep="\n  ")
        return 1
    print("Up to date." if not stale else "Wrote:\n  " + "\n  ".join(map(str, stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
