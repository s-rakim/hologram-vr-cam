"""Regenerate every CAD output from cad/spec.py.

    python -m cad.generate          # write all outputs
    python -m cad.generate --check  # fail if committed outputs are stale

Outputs:
    cad/out/hologram_glasses.ifc               open directly in Revit (File > Open > IFC)
    cad/revit/hologram_glasses_model.json      read by cad/revit/build_hologram_glasses.py
    docs/drawings/*.svg                        assembly, exploded, orthographic, wiring
    docs/bom.md, docs/wiring.md                bill of materials and pin table
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .ifc_writer import build_ifc
from .schematic import draw_schematic
from .spec import BOM, DEVICES, MATERIALS, PARTS, PI_HEADER, WIRES, overall_envelope
from .svg_draw import draw_assembly, draw_exploded, draw_orthographic

ROOT = Path(__file__).resolve().parent.parent


def model_json() -> str:
    env = overall_envelope()
    parts = []
    for p in PARTS:
        solids = []
        for s in p.solids:
            loops = [[[round(c, 4) for c in s.point3(pt, s.start)] for pt in loop] for loop in s.loops()]
            solids.append({"plane": s.plane, "normal": list(s.normal), "depth": round(s.depth, 4), "loops": loops})
        parts.append({"id": p.id, "name": p.name, "group": p.group, "material": p.material, "solids": solids})
    doc = {
        "name": "Hologram VR Cam glasses",
        "units": "mm",
        "axes": "X = wearer's right, Y = forward, Z = up; origin = bridge centre, back face of front frame",
        "envelope_mm": {"width": env.width, "depth": env.depth, "height": env.height},
        "materials": {k: {"name": m.name, "rgb": list(m.rgb), "transparency": m.transparency}
                      for k, m in MATERIALS.items()},
        "parts": parts,
    }
    return json.dumps(doc, indent=1) + "\n"


def bom_md() -> str:
    used: dict[str, list[str]] = {}
    for p in PARTS:
        if p.bom:
            used.setdefault(p.bom, []).append(p.name)
    lines = [
        "# Bill of materials",
        "",
        "<!-- Generated by `python -m cad.generate` from cad/spec.py. Edit the spec, not this file. -->",
        "",
        "Part numbers are examples; any equivalent with the same size and interface works.",
        "",
        "| # | Qty | Item | Spec | Model parts | Notes |",
        "|---|-----|------|------|-------------|-------|",
    ]
    for i, line in enumerate(BOM, 1):
        parts = ", ".join(sorted(set(used.get(line.key, [])))) or "-"
        lines.append(f"| {i} | {line.qty} | {line.item} | {line.spec} | {parts} | {line.notes} |")
    return "\n".join(lines) + "\n"


def wiring_md() -> str:
    def end(e: tuple[str, str]) -> str:
        dev, pin = e
        if dev == "pi":
            return f"Pi pin {pin} ({PI_HEADER[int(pin)]})" if pin.isdigit() else f"Pi {pin}"
        return f"{DEVICES[dev].name} `{pin}`"

    lines = [
        "# Wiring",
        "",
        "<!-- Generated by `python -m cad.generate` from cad/spec.py. Edit the spec, not this file. -->",
        "",
        "Pin numbers are physical Raspberry Pi header positions (the Pi Zero 2 W pads are numbered the same way).",
        "See `docs/drawings/04_wiring.svg` for the schematic.",
        "",
        "| Type | From | To | Notes |",
        "|------|------|----|-------|",
    ]
    for w in WIRES:
        lines.append(f"| {w.kind} | {end(w.a)} | {end(w.b)} | {w.note} |")
    lines += ["", "## Where each module lives", "", "| Module | Location |", "|--------|----------|"]
    lines += [f"| {d.name} | {d.location} |" for d in DEVICES.values()]
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    return {
        ROOT / "cad/out/hologram_glasses.ifc": build_ifc(),
        ROOT / "cad/revit/hologram_glasses_model.json": model_json(),
        ROOT / "docs/drawings/01_assembly.svg": draw_assembly(),
        ROOT / "docs/drawings/02_exploded.svg": draw_exploded(),
        ROOT / "docs/drawings/03_orthographic.svg": draw_orthographic(),
        ROOT / "docs/drawings/04_wiring.svg": draw_schematic(),
        ROOT / "docs/bom.md": bom_md(),
        ROOT / "docs/wiring.md": wiring_md(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if any output is out of date")
    args = parser.parse_args(argv)

    stale = []
    for path, content in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and stale:
        print("Out of date (run python -m cad.generate):", *stale, sep="\n  ")
        return 1
    print("Up to date." if not stale else "Wrote:\n  " + "\n  ".join(map(str, stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
